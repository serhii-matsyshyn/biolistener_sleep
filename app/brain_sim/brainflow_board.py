"""
BrainFlow-compatible synthetic brain board.

Spawns a TCP server that speaks the BioListener wire protocol (matching the
official BioListener emulator vendored into BrainFlow CI). When BrainFlow's
``BoardIds.BIOLISTENER_BOARD`` connects, it receives 8-channel EEG samples
generated by the Jansen-Rit NMM - same code path as the real device.

This gives true plug-and-play: pointing ``BoardShim`` at this TCP server
or at the real ESP32 BioListener is a configuration change, not a code
change.

Wire format (per user-supplied BioListener emulator reference):
    DataPacket = struct.pack('=1B 1I 1B 1I 1B 8I 1B',
        header=0xA0, ts_ms=uint32, type=uint8, packet_num=uint32,
        s_id=uint8, *eight_channel_uint24, footer=0xC0)
    packet type 1 = biosignals (the only type emitted here)

Control commands accepted (all JSON, newline-delimited, sent by BrainFlow):
    command 1..4 -> ignored (config commands)
    command 5    -> start stream
    command 6    -> stop stream
"""

from __future__ import annotations

import enum
import json
import logging
import socket
import struct
import threading
import time
from typing import Optional

import numpy as np

from .nmm import MultiChannelBrain
from .photic_input import (
    PhoticInputConfig, StrobeParams, strobe_to_cortical_input, vigilance_drift,
)

logger = logging.getLogger("brain_sim.brainflow_board")


# BioListener wire-format constants
PACKET_HEADER = 0xA0
PACKET_FOOTER = 0xC0
PACKET_TYPE_BIOSIGNALS = 1
ADC_S_ID_ADS131M08 = 0

PACKET_FORMAT = "=1B 1I 1B 1I 1B 8I 1B"


def volts_to_adc_code(
    voltage_uv: float,
    ref_uv: float = 2_500_000.0,
    pga_gain: int = 8,
    adc_resolution: float = 16_777_216.0,
) -> int:
    """
    Inverse of BrainFlow's ADC-code-to-microvolts conversion for ADS131M08.

    Default reference 2.5V (in µV) and 24-bit ADC resolution match the
    BioListener emulator the user provided.
    """
    resolution = ref_uv / (adc_resolution * pga_gain)
    if voltage_uv >= 0:
        raw = int(voltage_uv / resolution)
    else:
        raw = int((voltage_uv + (ref_uv / pga_gain)) / resolution)
    return max(0, min(0xFFFFFF, raw))


class _ServerState(enum.Enum):
    WAITING = "waiting"
    STREAMING = "streaming"


class NMMBioListenerDevice(threading.Thread):
    """
    NMM-driven impersonation of a BioListener device, protocol-compatible
    with BrainFlow's ``BoardIds.BIOLISTENER_BOARD`` driver.

    **Transport (mirroring the user-provided BioListener emulator):** this
    runs as a TCP *client* that connects outbound to BrainFlow's listening
    socket. BrainFlow binds the port (set via ``BrainFlowInputParams.ip_port``,
    default 12345 with auto-increment) and accepts our inbound connection.

    On that single bidirectional socket we receive newline-delimited JSON
    commands (5 = start stream, 6 = stop, 1..4 = ignored config) and send
    binary DataPackets in the BioListener wire format.

    For tight training loops use :class:`InProcessBrainSim` instead - it
    bypasses TCP entirely.
    """

    def __init__(
        self,
        brain: Optional[MultiChannelBrain] = None,
        photic_config: Optional[PhoticInputConfig] = None,
        host: str = "127.0.0.1",
        port: int = 12345,
        pga_gain: int = 8,
        adc_ref_uv: float = 2_500_000.0,
        emit_scale_uv: float = 50.0,
        connect_timeout: float = 10.0,
    ):
        super().__init__(daemon=True)
        self.brain = brain or MultiChannelBrain()
        self.photic_config = photic_config or PhoticInputConfig()
        self.host = host
        self.port = port
        self.pga_gain = pga_gain
        self.adc_ref_uv = adc_ref_uv
        self.emit_scale_uv = emit_scale_uv
        self.connect_timeout = connect_timeout

        self._strobe = StrobeParams()
        self._strobe_lock = threading.Lock()

        self._state = _ServerState.WAITING
        self._keep_alive = True
        self._packet_num = 0
        self._started_at: Optional[float] = None
        self._sock: Optional[socket.socket] = None
        self._connected = threading.Event()

    def update_strobe(self, strobe: StrobeParams) -> None:
        """Thread-safe strobe parameter update - called by the agent."""
        with self._strobe_lock:
            self._strobe = StrobeParams(
                enabled=strobe.enabled,
                frequency_hz=strobe.frequency_hz,
                fill=strobe.fill,
                brightness=strobe.brightness,
                color=strobe.color,
            )

    def stop(self) -> None:
        self._keep_alive = False

    @property
    def packet_count(self) -> int:
        return self._packet_num

    def wait_until_connected(self, timeout: float = 10.0) -> bool:
        return self._connected.wait(timeout=timeout)

    def run(self) -> None:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        sock.settimeout(0.5)
        self._sock = sock

        deadline = time.time() + self.connect_timeout
        logger.info("NMM device connecting to BrainFlow at %s:%d", self.host, self.port)
        while self._keep_alive and time.time() < deadline:
            try:
                sock.connect((self.host, self.port))
                self._connected.set()
                logger.info("Connected to BrainFlow")
                break
            except (ConnectionRefusedError, OSError) as err:
                logger.debug("Not yet listening (%s); retrying", err)
                time.sleep(0.1)
        if not self._connected.is_set():
            logger.error("Failed to connect to BrainFlow within %.1fs",
                         self.connect_timeout)
            return

        # Switch to non-blocking-ish recv for the main loop
        sock.settimeout(0.001)
        dt = self.brain.dt
        self._started_at = time.time()

        while self._keep_alive:
            self._poll_commands()
            if self._state == _ServerState.STREAMING:
                if not self._emit_one_sample():
                    break
                time.sleep(dt)
            else:
                time.sleep(0.01)

        self._close()

    def _poll_commands(self) -> None:
        if self._sock is None:
            return
        try:
            data = self._sock.recv(4096)
        except (socket.timeout, TimeoutError):
            return
        except OSError:
            return
        if not data:
            return
        for line in data.decode("utf-8", errors="ignore").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                msg = json.loads(line)
            except json.JSONDecodeError:
                logger.warning("Bad JSON from BrainFlow: %r", line)
                continue
            cmd = msg.get("command")
            if cmd in (1, 2, 3, 4):
                logger.debug("Config command %s ignored by sim", cmd)
            elif cmd == 5:
                logger.info("Start stream command received")
                self._state = _ServerState.STREAMING
            elif cmd == 6:
                logger.info("Stop stream command received")
                self._state = _ServerState.WAITING
            else:
                logger.warning("Unknown command: %s", cmd)

    def _emit_one_sample(self) -> bool:
        if self._sock is None:
            return False
        t = time.time() - (self._started_at or time.time())
        with self._strobe_lock:
            photic = strobe_to_cortical_input(t, self._strobe, self.photic_config)
        sample = self.brain.step(photic_input=photic)  # shape (8,) NMM mV-ish
        sample_uv = sample * self.emit_scale_uv
        codes = [
            volts_to_adc_code(v, ref_uv=self.adc_ref_uv, pga_gain=self.pga_gain)
            for v in sample_uv
        ]
        ts_ms = int(t * 1000) & 0xFFFFFFFF
        packet = struct.pack(
            PACKET_FORMAT,
            PACKET_HEADER,
            ts_ms,
            PACKET_TYPE_BIOSIGNALS,
            self._packet_num,
            ADC_S_ID_ADS131M08,
            *codes,
            PACKET_FOOTER,
        )
        try:
            self._sock.sendall(packet)
        except (ConnectionResetError, BrokenPipeError, OSError) as err:
            logger.warning("BrainFlow connection lost: %s", err)
            return False
        self._packet_num += 1
        return True

    def _close(self) -> None:
        if self._sock is not None:
            try:
                self._sock.close()
            except OSError:
                pass
            self._sock = None
        logger.info("NMM device stopped (emitted %d packets)", self._packet_num)


# Backwards-compat alias for early imports
NMMBioListenerServer = NMMBioListenerDevice


class InProcessBrainSim:
    """
    Fast in-process brain for RL training (no TCP roundtrip).

    Used by ``app/agent/env.py`` during the bulk of training. The same NMM
    instance gives bit-identical behaviour to NMMBioListenerServer for the
    same seed; only the transport differs.

    **Vigilance drift** is applied each step: the brain's background
    cortical drive (p_mean / p_std) is multiplied by an arousal factor
    that decays linearly over ``session_duration_s``, mimicking the
    ascending-reticular activating system gradually disengaging. The
    NMM's spectrum naturally tilts θ-ward as p_mean drops - that's the
    organic drowsiness signal the agent learns to detect and accelerate.
    """

    def __init__(
        self,
        brain: Optional[MultiChannelBrain] = None,
        photic_config: Optional[PhoticInputConfig] = None,
        session_duration_s: float = 60.0,
        vigilance_drift_enabled: bool = True,
    ):
        self.brain = brain or MultiChannelBrain()
        self.photic_config = photic_config or PhoticInputConfig()
        self._strobe = StrobeParams()
        self._t = 0.0
        # Stash the brain's baseline drive so we can multiply-then-restore
        # the vigilance modulation each step without permanently mutating
        # the underlying NMM.
        self.session_duration_s = float(session_duration_s)
        self.vigilance_drift_enabled = vigilance_drift_enabled
        self._base_p_mean = self.brain.p_mean
        self._base_p_std = self.brain.p_std

    def update_strobe(self, strobe: StrobeParams) -> None:
        self._strobe = strobe

    def step(self) -> np.ndarray:
        if self.vigilance_drift_enabled:
            m_mean, m_std = vigilance_drift(self._t, self.session_duration_s)
            self.brain.p_mean = self._base_p_mean * m_mean
            self.brain.p_std = self._base_p_std * m_std
        photic = strobe_to_cortical_input(self._t, self._strobe, self.photic_config)
        sample = self.brain.step(photic_input=photic)
        self._t += self.brain.dt
        return sample
